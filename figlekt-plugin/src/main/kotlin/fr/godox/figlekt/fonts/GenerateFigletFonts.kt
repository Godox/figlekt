package fr.godox.figlekt.fonts

import java.io.File
import java.io.InputStream
import java.net.URI
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import fr.godox.figlekt.generator.FigletFontGenerator

/**
 * Generates, for a source set, one `FigletFont` class and one `Font` extension per selected FIGlet font,
 * the font content itself being embedded as plain Kotlin source.
 *
 * The generation itself is delegated to [FigletFontGenerator], the very same code
 * running in the Kotlin/Wasm web page.
 */
@CacheableTask
abstract class GenerateFigletFonts : DefaultTask() {

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val fonts: ConfigurableFileCollection

    /**
     * The identifiers of the selected fonts, prefixed by `catalog:`, `file:` or `url:`.
     * All the [fonts] are compiled when empty.
     */
    @get:Input
    abstract val specs: ListProperty<String>

    /**
     * Whether the fonts of this source set are generated here: only one source set generates the fonts
     * configured globally, the other ones only generate the fonts of their own directory.
     */
    @get:Input
    abstract val generate: Property<Boolean>

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val figlektPackage: Property<String>

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        val outputDir = output.get().asFile
        outputDir.deleteRecursively()
        outputDir.mkdirs()
        if (!generate.get()) {
            outputDir.resolve("FigletFonts.kt").writeText("", Charsets.UTF_8)
            return
        }
        val sources = resolveSources()
        val functions = HashSet<String>()
        val fonts = LinkedHashMap<String, ByteArray>()
        for (source in sources) {
            val function = FigletFontGenerator.functionName(source.filename)
            if (!functions.add(function)) {
                throw GradleException("Duplicate font extension '$function' generated from '${source.filename}'")
            }
            fonts[source.filename] = source.content
        }
        val source = FigletFontGenerator.generate(fonts, packageName.get(), figlektPackage.get())
        outputDir.resolve("FigletFonts.kt")
            .writeText("// Generated by the fr.godox.figlekt.fonts plugin, do not edit.\n$source", Charsets.UTF_8)
    }

    private fun resolveSources(): List<Source> {
        val files = fonts.files.filter { it.isFile && it.name.endsWith(".flf", ignoreCase = true) }
            .sortedBy { it.name }
        val specs = specs.get()
        if (specs.isEmpty()) {
            return files.map { Source(it.name, readContent(it)) }
        }
        val all = specs.any { it == "${FigletSpec.KIND_CATALOG}:" }
        val sources = mutableListOf<Source>()
        val filenames = HashSet<String>()
        for (spec in specs) {
            if (spec == "${FigletSpec.KIND_CATALOG}:") {
                for (file in files) {
                    if (filenames.add(file.name)) {
                        sources.add(Source(file.name, readContent(file)))
                    }
                }
                continue
            }
            val kind = spec.substringBefore(':')
            val location = spec.substringAfter(':')
            val source = when (kind) {
                FigletSpec.KIND_CATALOG -> {
                    val file = files.firstOrNull { normalize(it.name) == normalize(location) }
                        ?: throw GradleException(
                            "The FIGlet font '$location' is not found in " +
                                    "${files.map { it.parent }.distinct().joinToString()}, " +
                                    "add it to the fonts directory or select it with +file()"
                        )
                    Source(file.name, readContent(file))
                }
                FigletSpec.KIND_FILE -> {
                    val file = File(location)
                    if (!file.isFile) {
                        throw GradleException("The FIGlet font file '$location' does not exist")
                    }
                    Source(file.name, readContent(file))
                }
                FigletSpec.KIND_URL -> Source(
                    location.substringAfterLast('/').substringBefore('?'),
                    download(location),
                )
                else -> throw GradleException("Unknown font spec '$spec'")
            }
            if (filenames.add(source.filename)) {
                sources.add(source)
            }
        }
        return sources
    }

    private class Source(val filename: String, val content: ByteArray)

    private fun normalize(filename: String): String {
        val builder = StringBuilder()
        for (c in filename) {
            if (c.isLetterOrDigit()) {
                builder.append(c.lowercaseChar())
            }
        }
        return builder.toString()
    }

    private fun readContent(file: File): ByteArray {
        val bytes = file.readBytes()
        val zipped = bytes.size >= 4 &&
                bytes[0] == 0x50.toByte() &&
                bytes[1] == 0x4b.toByte() &&
                bytes[2] == 0x03.toByte() &&
                bytes[3] == 0x04.toByte()
        if (!zipped) {
            return bytes
        }
        return try {
            java.util.zip.ZipInputStream(java.io.ByteArrayInputStream(bytes)).use { zipStream ->
                val entry = zipStream.getNextEntry() ?: throw GradleException("Font archive contains no entry")
                val buffer = java.io.ByteArrayOutputStream()
                zipStream.copyTo(buffer)
                buffer.toByteArray()
            }
        } catch (e: Exception) {
            throw GradleException("Failed to decode font '${file.name}'", e)
        }
    }

    private fun download(url: String): ByteArray {
        return try {
            URI(url).toURL().openStream().use(InputStream::readBytes)
        } catch (e: Exception) {
            throw GradleException("Failed to download the FIGlet font '$url'", e)
        }
    }
}